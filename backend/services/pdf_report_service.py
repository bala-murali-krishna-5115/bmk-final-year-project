import os
import io
from datetime import datetime
from typing import Dict, Any, Optional

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether
)

class PDFReportService:
    """
    Generates a publication-grade PDF screening report for multimodal health screening sessions.
    Includes visual appearance metrics (dark circles, tiredness, blemishes, erythema, hair),
    ESP-32 hardware physiological vitals (if connected), tri-model comparative analysis,
    SHAP explainability, and personalized resting and wellness recommendations.
    
    Academic Policy: NO static / rough data. If hardware is missing, vital signs are reported
    as unavailable rather than fabricating placeholder numbers.
    """

    @classmethod
    def generate_report(cls, session_data: Dict[str, Any]) -> bytes:
        """
        Builds PDF report in memory and returns raw PDF bytes.
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()

        # Custom Typography Styles
        title_style = ParagraphStyle(
            'DocTitle', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=16, leading=20,
            textColor=colors.HexColor('#0F172A')
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=9, leading=13,
            textColor=colors.HexColor('#0284C7')
        )
        section_heading = ParagraphStyle(
            'SectionHeading', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=10, leading=14,
            textColor=colors.HexColor('#0F172A'), spaceBefore=8, spaceAfter=4
        )
        body_style = ParagraphStyle(
            'BodyTextCustom', parent=styles['Normal'],
            fontName='Helvetica', fontSize=8, leading=11,
            textColor=colors.HexColor('#334155')
        )
        body_bold = ParagraphStyle(
            'BodyBoldCustom', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=8, leading=11,
            textColor=colors.HexColor('#0F172A')
        )
        disclaimer_style = ParagraphStyle(
            'DisclaimerText', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=7.5, leading=10,
            textColor=colors.HexColor('#991B1B')
        )
        cell_header_style = ParagraphStyle(
            'CellHeader', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=7.5, leading=9,
            textColor=colors.white
        )
        cell_body_style = ParagraphStyle(
            'CellBody', parent=styles['Normal'],
            fontName='Helvetica', fontSize=7.5, leading=10,
            textColor=colors.HexColor('#1E293B')
        )
        cell_bold_style = ParagraphStyle(
            'CellBodyBold', parent=styles['Normal'],
            fontName='Helvetica-Bold', fontSize=7.5, leading=10,
            textColor=colors.HexColor('#0F172A')
        )

        story = []

        # 1. Header Section
        session_id = session_data.get("session_id", "N/A")
        user_code = session_data.get("user_code", "Anonymous")
        timestamp = session_data.get("timestamp", datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"))
        status = session_data.get("status", "completed").upper()

        story.append(Paragraph("AI-BASED MULTIMODAL HEALTH SCREENING SYSTEM", title_style))
        story.append(Paragraph("RESEARCH SCREENING REPORT, APPEARANCE FINDINGS & REST RECOMMENDATIONS", subtitle_style))
        story.append(Spacer(1, 6))

        # Metadata Table
        meta_table_data = [
            [Paragraph("<b>Session ID:</b> " + str(session_id), body_style), Paragraph("<b>User Code:</b> " + str(user_code), body_style)],
            [Paragraph("<b>Date / Time:</b> " + str(timestamp), body_style), Paragraph("<b>Screening Status:</b> " + str(status), body_style)]
        ]
        meta_table = Table(meta_table_data, colWidths=[270, 270])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 6))

        # 2. Prominent Disclaimer Banner
        disclaimer_html = (
            "<b>IMPORTANT RESEARCH DISCLAIMER:</b> This report is generated by a preliminary screening and appearance analysis tool. "
            "It is <b>NOT</b> a 100% prescribed or clinical diagnostic tool. Visual appearance findings (dark circles, blemishes, redness) "
            "and physiological readings do not replace medical evaluation by a licensed healthcare professional or dermatologist."
        )
        disclaimer_table = Table([[Paragraph(disclaimer_html, disclaimer_style)]], colWidths=[540])
        disclaimer_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#FEF2F2')),
            ('BOX', (0, 0), (-1, -1), 1.0, colors.HexColor('#EF4444')),
            ('PADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(disclaimer_table)
        story.append(Spacer(1, 8))

        # 3. Overall Screening Verdict & Anomaly Summary
        screening = session_data.get("screening_results", {})
        verdict = screening.get("screening_verdict", "Screening Completed")
        risk_level = screening.get("risk_level", "Low")
        anom = screening.get("anomaly_analysis", {})
        anomaly_score = anom.get("anomaly_score", 0.0)
        anomaly_flag = anom.get("anomaly_flag", False)
        hw_connected = screening.get("hardware_connected", False)

        risk_color = '#10B981' if risk_level == "Low" else ('#F59E0B' if risk_level == "Moderate" else '#EF4444')

        verdict_data = [
            [
                Paragraph(f"<b>Overall Pattern Verdict:</b> <font color='{risk_color}'><b>{verdict}</b></font>", body_style),
                Paragraph(f"<b>Risk Classification:</b> <font color='{risk_color}'><b>{risk_level}</b></font>", body_style)
            ],
            [
                Paragraph(f"<b>Isolation Forest Anomaly Score:</b> {anomaly_score:.3f} (0.0=Normal, 1.0=Anomaly)", body_style),
                Paragraph(f"<b>ESP-32 Hardware Status:</b> <font color='{'#10B981' if hw_connected else '#DC2626'}'><b>{'CONNECTED' if hw_connected else 'DISCONNECTED / MISSING'}</b></font>", body_style)
            ]
        ]
        verdict_table = Table(verdict_data, colWidths=[310, 230])
        verdict_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F1F5F9')),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#94A3B8')),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(verdict_table)
        story.append(Spacer(1, 8))

        # 4. Intelligent Health Findings & Resting Recommendations Box
        health_rep = screening.get("health_report", {})
        story.append(Paragraph("Executive Health Findings & Rest Recommendations", section_heading))

        rec_paragraphs = []
        exec_summary = health_rep.get("executive_summary", "Appearance analysis completed.")
        rec_paragraphs.append(Paragraph(f"<b>Summary:</b> {exec_summary}", body_bold))

        for rec in health_rep.get("specific_recommendations", []):
            rec_paragraphs.append(Paragraph(f"&bull; <b>Actionable Recommendation:</b> {rec}", body_style))

        if not hw_connected:
            rec_paragraphs.append(Paragraph("<b>Hardware Note:</b> Physical ESP-32 hardware sensors are disconnected. Vitals (HR, SpO2, Temp) were omitted to prevent inaccurate rough data.", body_style))

        rec_table_data = [[p] for p in rec_paragraphs]
        rec_table = Table(rec_table_data, colWidths=[540])
        rec_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F0FDF4')),
            ('BOX', (0, 0), (-1, -1), 1.0, colors.HexColor('#16A34A')),
            ('PADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(rec_table)
        story.append(Spacer(1, 8))

        # 5. Computer Vision Appearance Analysis Matrix
        story.append(Paragraph("1. Computer Vision Facial Appearance Analysis (Eyes, Skin, Hair)", section_heading))

        app_analysis = screening.get("appearance_analysis", {})
        dark = app_analysis.get("dark_circles", {})
        tired = app_analysis.get("tiredness", {})
        blem = app_analysis.get("blemishes_and_acne", {})
        pig = app_analysis.get("pigmentation_and_redness", {})
        hair = app_analysis.get("hair_and_scalp", {})

        app_data = [
            [
                Paragraph("Appearance Module", cell_header_style),
                Paragraph("Specific Visual Finding", cell_header_style),
                Paragraph("Severity / Metric Value", cell_header_style),
                Paragraph("Screening Interpretation", cell_header_style)
            ],
            [
                Paragraph("Under-Eye Dark Circles", cell_bold_style),
                Paragraph(f"Infraorbital contrast &Delta;L*: {dark.get('contrast_delta_l', 0)}", cell_body_style),
                Paragraph(f"{dark.get('severity', 'Minimal')} ({dark.get('darkness_index_percentage', 0)}%)", cell_bold_style),
                Paragraph(dark.get('recommendation', 'Nominal periorbital appearance')[:75] + '...', cell_body_style)
            ],
            [
                Paragraph("Eye Fatigue & Droopiness", cell_bold_style),
                Paragraph(f"EAR Openness: {screening.get('features_summary', {}).get('vision_highlights', {}).get('mean_eye_openness', 0.28)}", cell_body_style),
                Paragraph(f"{tired.get('tiredness_level', 'Alert')} ({tired.get('tiredness_score', 0)}%)", cell_bold_style),
                Paragraph(tired.get('advice', 'Well-rested eye state')[:75] + '...', cell_body_style)
            ],
            [
                Paragraph("Acne & Skin Blemishes", cell_bold_style),
                Paragraph(f"Candidate Lesion Count: {blem.get('visible_lesion_count', 0)}", cell_body_style),
                Paragraph(f"{blem.get('blemish_severity', 'Clear')} ({blem.get('lesion_extent_percentage', 0)}% area)", cell_bold_style),
                Paragraph(blem.get('details', 'Facial skin appears clear')[:75] + '...', cell_body_style)
            ],
            [
                Paragraph("Erythema & Pigmentation", cell_bold_style),
                Paragraph(f"Erythema Index: {pig.get('erythema_index', 0)}", cell_body_style),
                Paragraph(f"Redness: {'Flagged' if pig.get('redness_flag') else 'Nominal'}", cell_bold_style),
                Paragraph(pig.get('summary', 'Balanced skin tone')[:75] + '...', cell_body_style)
            ],
            [
                Paragraph("Hair & Scalp Analysis", cell_bold_style),
                Paragraph(f"Hairline: {hair.get('hairline_stability', 'Normal')}", cell_body_style),
                Paragraph(f"Density Score: {hair.get('hair_density_score', 0)}%", cell_bold_style),
                Paragraph(hair.get('summary', 'Normal follicular appearance')[:75] + '...', cell_body_style)
            ]
        ]
        app_table = Table(app_data, colWidths=[115, 145, 115, 165])
        app_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0F766E')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8FAFC')]),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(app_table)
        story.append(Spacer(1, 8))

        # 6. Physiological Telemetry Section (NO FAKE DATA)
        story.append(Paragraph("2. Physiological Sensor Telemetry (ESP-32 MAX30102 & MLX90614)", section_heading))
        sensor_data = session_data.get("sensor_data")
        if not sensor_data or sensor_data.get("heart_rate") is None:
            no_hw_text = (
                "<b>Hardware Status:</b> <font color='#DC2626'><b>DISCONNECTED / NOT DETECTED</b></font><br/>"
                "Physiological measurements (Heart Rate, SpO2, Temperature) are not displayed because physical hardware is not transmitting. "
                "The system strictly prohibits synthetic rough data in place of real hardware telemetry."
            )
            no_hw_table = Table([[Paragraph(no_hw_text, body_style)]], colWidths=[540])
            no_hw_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#FFFBEB')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#F59E0B')),
                ('PADDING', (0, 0), (-1, -1), 6),
            ]))
            story.append(no_hw_table)
        else:
            sensor_table_data = [
                [
                    Paragraph("Vital Measurement", cell_header_style),
                    Paragraph("Observed Value", cell_header_style),
                    Paragraph("Normal Resting Range", cell_header_style),
                    Paragraph("Sensor Quality Status", cell_header_style)
                ],
                [
                    Paragraph("Heart Rate (Pulse)", cell_bold_style),
                    Paragraph(f"{sensor_data.get('heart_rate')} bpm", cell_body_style),
                    Paragraph("60.0 - 100.0 bpm", cell_body_style),
                    Paragraph("Valid Signal (PPG)", cell_body_style)
                ],
                [
                    Paragraph("Blood Oxygen (SpO2)", cell_bold_style),
                    Paragraph(f"{sensor_data.get('spo2')} %", cell_body_style),
                    Paragraph("95.0 - 100.0 %", cell_body_style),
                    Paragraph("Valid Signal (Red/IR)", cell_body_style)
                ],
                [
                    Paragraph("Body Temperature", cell_bold_style),
                    Paragraph(f"{sensor_data.get('temperature')} °C", cell_body_style),
                    Paragraph("36.1 - 37.2 °C", cell_body_style),
                    Paragraph("Valid Signal (Infrared)", cell_body_style)
                ]
            ]
            sensor_table = Table(sensor_table_data, colWidths=[135, 135, 135, 135])
            sensor_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1E293B')),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
                ('PADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(sensor_table)
        story.append(Spacer(1, 8))

        # 7. Tri-Model Comparative Evaluation
        story.append(Paragraph("3. Tri-Model Machine Learning Matrix", section_heading))
        tri_models = screening.get("tri_model_comparison", {})
        tri_data = [
            [
                Paragraph("Model Architecture", cell_header_style),
                Paragraph("Modality Type", cell_header_style),
                Paragraph("Status / Predicted Class", cell_header_style),
                Paragraph("Confidence Score", cell_header_style)
            ]
        ]
        for mod_key, label, inp_type in [
            ("model_a_sensor", "Model A: Hardware Only", "ESP-32 Sensor Array"),
            ("model_b_vision", "Model B: Vision Only", "Facial Landmarks & Skin Metrics"),
            ("model_c_multimodal", "Model C: Multimodal Fusion", "Early Feature Fusion (All Modalities)")
        ]:
            mod_res = tri_models.get(mod_key, {})
            p_class = mod_res.get("predicted_class")
            conf = mod_res.get("confidence")
            status_str = mod_res.get("status", "Active")
            if p_class is not None:
                p_text = f"{'Nominal (0)' if p_class == 0 else 'Deviation (1)'}"
                conf_text = f"{conf * 100:.1f}%" if conf else "N/A"
            else:
                p_text = status_str
                conf_text = "N/A"
            tri_data.append([
                Paragraph(label, cell_bold_style),
                Paragraph(inp_type, cell_body_style),
                Paragraph(p_text, cell_body_style),
                Paragraph(conf_text, cell_body_style)
            ])
        tri_table = Table(tri_data, colWidths=[135, 155, 150, 100])
        tri_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#334155')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(tri_table)
        story.append(Spacer(1, 8))

        # 8. Lifestyle Health Tips
        story.append(Paragraph("4. Recommended Health Tips to Maintain Vitality", section_heading))
        tips_paragraphs = [Paragraph(f"&bull; {tip}", body_style) for tip in health_rep.get("general_lifestyle_tips", [])]
        tips_table = Table([[p] for p in tips_paragraphs], colWidths=[540])
        tips_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(tips_table)
        story.append(Spacer(1, 10))

        # 9. Institutional Sign-off Block
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#CBD5E1'), spaceAfter=6))
        sign_data = [
            [
                Paragraph("<b>Principal Investigator / Student Lead:</b><br/>Bala Murali Krishna", body_style),
                Paragraph("<b>Dermatology Taxonomy References:</b><br/>SCIN &bull; Fitzpatrick17k &bull; HAM10000 &bull; DDI", body_style),
                Paragraph("<b>System Verification:</b><br/>Academic Research Prototype Passed", body_style)
            ]
        ]
        sign_table = Table(sign_data, colWidths=[180, 200, 160])
        sign_table.setStyle(TableStyle([('PADDING', (0, 0), (-1, -1), 3)]))
        story.append(sign_table)

        doc.build(story)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        return pdf_bytes
